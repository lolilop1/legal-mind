"""Нормализация адреса для отображения в PDF.

Логика:
1. Нормализуем сокращения с цифрами: д1 → д. 1, кв42 → кв. 42
2. НЕ удаляем существующие запятые
3. Добавляем запятую ПЕРЕД маркерами (ул., д., кв., корп., стр.),
   только если её там ещё нет.

Что НЕ трогаем: "Невский пр.", "Ленинский просп." — там "пр." часть названия.
"""

from __future__ import annotations

import re


def format_address(addr: str) -> str:
    if not addr:
        return addr

    s = addr.strip()

    # 1. Нормализация сокращений с цифрами
    s = re.sub(r"\bд(\d)", r"д. \1", s)
    s = re.sub(r"\bкв(\d)", r"кв. \1", s)
    s = re.sub(r"\bкорп(\d)", r"корп. \1", s)
    s = re.sub(r"\bстр(\d)", r"стр. \1", s)

    # 2. Множественные пробелы → один
    s = re.sub(r"\s+", " ", s).strip()

    # 3. Добавить запятую перед маркерами, если её нет
    #    [^,] — символ перед пробелом не запятая
    s = re.sub(r"([^,])\s+(ул\.|д\.|кв\.|корп\.|стр\.)", r"\1, \2", s)

    # 4. Убрать дубликаты запятых и запятую перед точкой
    s = re.sub(r",\s*,", ",", s)
    s = re.sub(r",\s*\.", ".", s)
    s = re.sub(r"\s+", " ", s).strip()

    return s