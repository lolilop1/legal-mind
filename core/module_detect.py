"""Авто-детект модуля (uk/noise/consumer) по тексту.

⚠️ СТАТУС: ЗАДЕЛ. НЕ подключён к app.py.
Будет активирован когда все модули будут раздуты
(потребитель, шум, уголовный, труд, аренда, семья, авто).

Порядок: сначала специфичные триггеры, потом общие.
Возвращает "uk" | "noise" | "consumer" | None.
None = не уверен → caller показывает карточки.
"""

from __future__ import annotations

import re


# ═══ Потребитель: покупка/товар/услуга ═══
_CONSUMER = re.compile(
    r"\bкупил|\bкупила|приобр[её]л|приобр[её]ла|заказал|заказала|"
    r"оплатил|оплатила|продавец|магазин|маркетплейс|ozon|озон|"
    r"wildberries|вайлдберриз|avito|авито|\bтовар|гаранти|"
    r"брак|дефект|не\s*подошл|вернуть\s*товар|возврат\s*товар|"
    r"услуг|исполнител|курс|обучени|доставк|курьер|"
    r"\bбанк|\bкредит|микрозайм|страхов|осаго|каско|"
    r"\bтур|пут[её]вк|отел|стоматолог|косметолог",
    re.IGNORECASE,
)

# ═══ Шум: сосед шумит, тишина, музыка ═══
_NOISE = re.compile(
    r"тишин|не\s*да[её]т\s*спать|не\s*могу\s*спать|"
    r"\bшум|шумн|шумят|шумит|громк.{0,10}музык|музык.{0,15}(?:ноч|громк)|"
    r"\bтопот|топают|\bсверл|\bдолб|"
    r"\bлай|\bлает|\bлают|"
    r"\bкрич|\bорут|\bор[её]т|дебош|скандал.{0,15}(?:сосед|ноч)|"
    r"вечеринк|гулянк|"
    r"после\s*22|после\s*23|ночн.{0,10}(?:шум|музык|громк)",
    re.IGNORECASE,
)

# ═══ УК / ЖКХ: дом, подъезд, коммуналка ═══
_UK = re.compile(
    r"управляющ.{0,15}компан|\bУК\b|"
    r"подъезд|чердак|подвал|крыш|кровл|фасад|фундамент|"
    r"лифт|домофон|мусоропровод|"
    r"батаре|отоплен|радиатор|холодн.{0,15}вод|горяч.{0,15}вод|"
    r"\bГВС|\bХВС|"
    r"залил|затопил|протечк|теч[её]т.{0,15}(?:крыш|потолок)|"
    r"капремонт|канализац|вентиляц|"
    r"\bГЖИ|госжилинспекц|"
    r"сосульк|налед|голол[её]д|"
    r"мусор.{0,15}(?:подъезд|двор|контейнер)|"
    r"контейнерн.{0,15}площадк|"
    r"общ.{0,15}имуществ.{0,15}дом|"
    r"сантехник|стояк|"
    r"управляшк|управляющ",
    re.IGNORECASE,
)


def detect_module(text: str) -> str | None:
    """Определяет модуль по тексту.

    Returns: "uk" | "noise" | "consumer" | None.
    None = не уверен.
    """
    if not text or len(text.strip()) < 10:
        return None

    s = text.lower()

    # ═══ КОНФЛИКТЫ — сначала разрешаем ═══
    # "сосед сверху залил" → УК (затопление), НЕ шум
    if re.search(r"(?:залил|затопил|протечк)", s):
        return "uk"
    # "сосед сверху шумит/музыка" → шум
    if re.search(r"(?:сосед|сверху|снизу|за\s*стен)", s) and \
       re.search(r"(?:шум|музык|топот|крич|лай|долб|сверл)", s):
        return "noise"

    # ═══ Одиночные сигналы ═══
    matches = {
        "consumer": bool(_CONSUMER.search(s)),
        "noise": bool(_NOISE.search(s)),
        "uk": bool(_UK.search(s)),
    }
    found = [k for k, v in matches.items() if v]

    if len(found) == 1:
        return found[0]
    if len(found) == 0:
        return None
    # Несколько совпадений → не уверен, пусть юзер выберет
    return None
