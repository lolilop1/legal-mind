"""Определение сценария потребительского спора по тексту описания.

Порядок проверок (первое совпадение выигрывает):
1. marketplace — явно упомянут маркетплейс
2. service     — явно про услугу/работу
3. return14    — товар не подошёл
4. defect      — товар сломан/брак
5. None        — не уверен (caller сам решит)
"""

from __future__ import annotations

import re


# ─── Маркетплейс ───
_MARKETPLACE = re.compile(
    r"ozon|озон|wildberries|вайлдберриз|\bwb\b|яндекс[\s\-]?маркет|"
    r"авито|avito|маркетплейс|дистанционн",
    re.IGNORECASE,
)


# ─── Услуга / работа ───
_SERVICE = re.compile(
    r"услуг|исполнител|подрядчик|"
    r"ремонт\s+(?:квартир|авто|техник|дом|офис)|"
    r"\bкурс|обучени|тренинг|вебинар|"
    r"стрижк|маникюр|педикюр|косметолог|массаж|"
    r"юрист|адвокат|"
    r"доставк|курьер|"
    r"не\s+оказал|не\s+выполнил|плохо\s+сделал|халтур|"
    r"некачественн|"
    # Банк / кредит
    r"\bбанк\w*|\bкредит|микрозайм|\bмфо\b|"
    r"кредитн\w*\s+карт|"
    r"навязал\w*|"
    # Страховая
    r"страхов\w*|осаго|каско|\bдмс\b|"
    r"страхов\w*\s+(?:выплат|возмещен)|"
    # Туризм
    r"\bтур\w*|пут[её]вк|туроператор|турагент",
    re.IGNORECASE,
)


# ─── Товар не подошёл (return14) ───
# Пишем явно и просто, без \s+ там где не нужно
_RETURN14 = re.compile(
    r"не\s*подош(?:[её]л|ла|ло|ли|ёл|ла|ло|ли)?|"
    r"не\s*подходит|не\s*подходят|"
    r"не\s*тот\s*размер|не\s*тот\s*цвет|"
    r"не\s*понравил(?:а|о|и|ся)?|"
    r"не\s*устроил(?:а|о|и)?|"
    r"хочу\s*вернуть|вернуть\s*товар|возврат\s*товара|"
    r"маломерит|большемерит|"
    r"не\s*по\s*размеру|не\s*по\s*росту|"
    r"не\s*по\s*цвету|не\s*того\s*цвета",
    re.IGNORECASE,
)


# ─── Товар сломан (defect) ───
# Расширяем: добавляем все формы "перестал X"
_DEFECT = re.compile(
    r"брак|дефект|сломал|"
    r"не\s*работ|"
    r"переста[л|ла|ли]?\s*(?:работ|включ|завод|функционир|заряжа)|"
    r"перестал|перестала|"
    r"неисправ|не\s*функционир|"
    r"вышел\s*из\s*строя|вышла\s*из\s*строя|"
    r"не\s*включа|не\s*заводит|"
    r"сломался|сломалась|поломал|"
    r"не\s*работает\s*должным|"
    # Гарантийный ремонт товара (это defect, не service)
    r"гарантийн\w*\s+ремонт|"
    r"сдал\w*\s+(?:телефон|техник|товар|устройств)|"
    r"отнёс\w*\s+(?:телефон|техник|товар|устройств|в\s+сервис|в\s+ремонт)|"
    r"отнес\w*\s+(?:телефон|техник|товар|устройств|в\s+сервис|в\s+ремонт)|"
    r"\bсервис\w*\s+центр|"
    r"отказ\w*\s+(?:в\s+)?ремонт|"
    r"не\s+гарантийн|"
    r"ремонт.{0,40}(?:третий\s+месяц|длится|свыше|больше\s+45)",
    re.IGNORECASE,
)


def detect_scenario(problem: str) -> str | None:
    """Определяет сценарий по тексту. None если не уверен.

    Порядок важен — сначала специфичные случаи.
    """
    if not problem:
        return None

    # 1. Маркетплейс
    if _MARKETPLACE.search(problem):
        return "marketplace"

    # 2. Услуга / работа
    if _SERVICE.search(problem):
        return "service"

    # 3-4. Приоритет: если есть ЯВНЫЕ признаки недостатка (сломан,
    # брак, не работает) — это defect (ст. 18), а не return14 (ст. 25).
    # «Хочу вернуть сломанный» ≠ «не подошёл по размеру».
    _has_defect_signal = _DEFECT.search(problem)
    _has_return14_signal = _RETURN14.search(problem)

    if _has_defect_signal:
        return "defect"
    if _has_return14_signal:
        return "return14"

    return None