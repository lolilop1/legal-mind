_COMPILED = [(code, re.compile(pat, re.IGNORECASE)) for code, pat in PATTERNS]


def detect_doc_type(text: str) -> str | None:
    """Возвращает code конфига или None если не уверен."""
    if not text:
        return None
    s = text.lower()
    for code, pat in _COMPILED:
        if pat.search(s):
            return code
    return None
