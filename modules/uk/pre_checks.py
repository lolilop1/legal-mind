def run_uk_pre_checks(user_data: dict, extras: dict | None = None) -> PreCheckReport:
    report = PreCheckReport()
    problem = (user_data.get("проблема") or "").strip()
    address = (user_data.get("адрес") or "").strip()
    date_started = (user_data.get("дата_начала") or "").strip()
    previous = (user_data.get("обращались_ранее") or "").strip()

    # Known
    add_known(report, "Тип проблемы", "Жалоба в управляющую компанию")
    if address:
        add_known(report, "Адрес", address)
    if date_started:
        add_known(report, "Дата начала", date_started)
    if previous and previous.lower() not in ("нет", ""):
        add_known(report, "Обращения ранее", previous)

    # Объект проблемы
    match = _OBJECT_PATTERNS.search(problem)
    if match:
        add_known(report, "Объект проблемы", _pretty_object(match.group(0)))
    else:
        add_missing_critical(
            report,
            "Объект проблемы",
            "Не указано, что именно нарушено — уборка, лифт, крыша, "
            "отопление, вода и т.п.",
        )

    # Дата начала — опционально
    if not date_started:
        add_missing_optional(
            report,
            "Дата начала",
            "Когда началось нарушение — усиливает жалобу.",
        )

    return report


def _pretty_object(raw: str) -> str:
    raw_lower = raw.lower()
    for key, value in _OBJECT_LABELS:
        if key in raw_lower:
            return value
    return raw