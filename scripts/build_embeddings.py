def load_laws() -> list[dict]:
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    cur = conn.execute(
        """
        SELECT region, law_name, prompt_version
        FROM noise_laws
        WHERE law_name IS NOT NULL AND law_name != '' AND law_name != '0'
        ORDER BY region
        """
    )
    rows = [dict(r) for r in cur.fetchall()]
    conn.close()

    priority = {"v3-hardcoded": 0, "v4-pro-host-filtered": 1, "v1-minimal": 2}
    canonical = {
        "Татарстан": "Республика Татарстан",
        "Башкортостан": "Республика Башкортостан",
        "Крым": "Республика Крым",
    }

    best: dict[str, dict] = {}
    for r in rows:
        region = canonical.get(r["region"], r["region"])
        ver = r.get("prompt_version", "")
        score = priority.get(ver, 99)
        if region not in best or score < priority.get(best[region]["prompt_version"], 99):
            best[region] = dict(r, region=region)

    return list(best.values())


def embed(text: str, model: str = "text-search-doc/latest") -> list[float] | None:
    headers = {
        "Authorization": f"Api-Key {API_KEY}",
        "Content-Type": "application/json",
    }
    body = {"modelUri": f"emb://{FOLDER_ID}/{model}", "text": text}
    try:
        r = requests.post(EMBED_URL, headers=headers, json=body, timeout=30)
    except requests.RequestException as e:
        print(f"  Сеть: {e}")
        return None
    if r.status_code != 200:
        print(f"  HTTP {r.status_code}: {r.text[:200]}")
        return None
    try:
        return r.json()["embedding"]
    except (KeyError, IndexError) as e:
        print(f"  Парсинг: {e}")
        return None


def build_text(region: str) -> str:
    cities = REGION_CITIES.get(region, [])
    if cities:
        return f"Регион: {region}. Города: {', '.join(cities)}."
    return f"Регион: {region}."


def main():
    if not API_KEY or not FOLDER_ID:
        print("Не настроены ключи")
        return

    print(f"БД:   {DB_PATH}")
    print(f"Файл: {OUT_PATH}")

    laws = load_laws()
    print(f"Загружено регионов: {len(laws)}")

    embeddings: dict[str, list[float]] = {}
    for i, law in enumerate(laws, 1):
        region = law["region"]
        text = build_text(region)
        vec = embed(text)
        if vec:
            embeddings[region] = vec
            cities_count = len(REGION_CITIES.get(region, []))
            print(f"  [{i}/{len(laws)}] {region:<45} OK ({cities_count} городов)")
        else:
            print(f"  [{i}/{len(laws)}] {region:<45} FAIL")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(embeddings, f, ensure_ascii=False)

    print(f"\nГотово. Сохранено {len(embeddings)} эмбеддингов в {OUT_PATH}")


if __name__ == "__main__":
    main()